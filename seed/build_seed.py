def normalize(text):
    return ' '.join(text.replace('\xa0', ' ').split()).rstrip('.').strip()


def read_sheet(ws):
    """Возвращает [(группа, уровень, текст, строка, ячейка_разбита)] по листу исходной матрицы."""
    has_level = ws.cell(1, 3).value == 'Навык'  # листы переходов: A группа, B уровень, C текст
    text_col = 3 if has_level else 2
    rows, group, level = [], None, None if has_level else ws.title
    for r in range(2, ws.max_row + 1):
        a = ws.cell(r, 1).value
        if a == 'Среднее':
            continue
        if a:
            group = GROUP_ALIASES.get(a.strip(), a.strip())
        if has_level and ws.cell(r, 2).value:
            level = ws.cell(r, 2).value.strip()
        raw = ws.cell(r, text_col).value
        if raw and str(raw).strip():
            # Ячейка с несколькими строками = несколько отдельных индикаторов
            parts = [p.strip() for p in str(raw).split('\n') if p.strip()]
            for part in parts:
                rows.append((group, level, part, r, len(parts) > 1))
    return rows


def main():
    wb = openpyxl.load_workbook(SRC)
    sheets = {ws.title: read_sheet(ws) for ws in wb.worksheets[1:]}

    result, log = [], []
    for group in GROUPS:
        for level in LEVEL_SOURCE:
            src = GAP_FILL.get((group, level), LEVEL_SOURCE[level])
            items = [x for x in sheets[src] if x[0] == group and x[1] == level and x[2] not in SKIP_TEXTS]
            if (group, level) in GAP_FILL:
                log.append((group, level, src, '', '', f'Пробел заполнен из листа {src}'))
            for order, (_, _, raw, row, was_split) in enumerate(items, 1):
                text = normalize(raw)
                fixed = FIXES.get(text, text)
                if fixed != text:
                    log.append((group, level, src, row, raw, f'Исправлено: {fixed}'))
                elif was_split:
                    log.append((group, level, src, row, raw, 'Ячейка разбита на отдельные индикаторы'))
                result.append((group, level, fixed, order))

    unused = set(FIXES) - {normalize(x[2]) for s in sheets.values() for x in s}
    assert not unused, f'Исправления не применились: {unused}'

    out = openpyxl.Workbook()
    ws = out.active
    ws.title = 'Матрица'
    ws.append(['Направление', 'Группа', 'Порядок группы', 'Грейд', 'Индикатор', 'Порядок'])
    for group, level, text, order in result:
        ws.append(['backend', group, GROUPS.index(group) + 1, level, text, order])

    lg = out.create_sheet('Изменения')
    lg.append(['Группа', 'Грейд', 'Лист-источник', 'Строка', 'Исходный текст', 'Изменение'])
    for row in log:
        lg.append(list(row))

    for sheet, widths in ((ws, [14, 30, 10, 8, 110, 10]), (lg, [30, 8, 14, 8, 70, 70])):
        for i, w in enumerate(widths, 1):
            sheet.column_dimensions[get_column_letter(i)].width = w
        for cell in sheet[1]:
            cell.font = Font(bold=True)
            cell.fill = PatternFill('solid', fgColor='DDEBF7')
        for row in sheet.iter_rows(min_row=2):
            for cell in row:
                cell.alignment = Alignment(wrap_text=True, vertical='top')
        sheet.freeze_panes = 'A2'
        sheet.auto_filter.ref = sheet.dimensions

    out.save(OUT)

    from collections import Counter
    c = Counter((g, l) for g, l, _, _ in result)
    print('Всего индикаторов:', len(result), '| записей в журнале:', len(log))
    print(f'{"":32}' + ''.join(f'{l:>4}' for l in LEVEL_SOURCE))
    for g in GROUPS:
        print(f'{g:32}' + ''.join(f'{c[(g, l)]:>4}' for l in LEVEL_SOURCE))


main()
